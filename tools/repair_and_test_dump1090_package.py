#!/usr/bin/env python3
r"""
Repair and retest the packaged Dump1090 runtime for RTL-Windows / RTP-Windows.

Run from MSYS2 UCRT64 repo root:
  python3 tools/repair_and_test_dump1090_package.py

What it does:
  - Finds the Windows service package Dump1090 folder.
  - Restores/copies dump1090.cfg into the same folder as dump1090.exe.
  - Copies service-package DLLs from package/bin next to dump1090.exe.
  - Runs dump1090 directly using device index 1 / serial 00001090.
  - Checks whether dump1090 stays running and opens expected ports.
  - Writes a report to C:/Users/jim/Downloads.

It does NOT call cmd.exe, PowerShell, or WSL.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import shutil
import socket
import subprocess
import sys
import time
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import urlopen


EXPECTED_ADSB_DEVICE_INDEX = "1"
EXPECTED_ADSB_SERIAL = "00001090"
TEST_SECONDS = 18

PORTS_TO_CHECK = [
    (30003, "SBS/BaseStation"),
    (30002, "raw output"),
    (30005, "Beast output"),
    (8080, "Dump1090 HTTP"),
    (8754, "Dump1090 alternate HTTP"),
]

JSON_URLS = [
    "http://127.0.0.1:8080/data/aircraft.json",
    "http://localhost:8080/data/aircraft.json",
    "http://127.0.0.1:8754/data/aircraft.json",
    "http://localhost:8754/data/aircraft.json",
]


def downloads_dir() -> Path:
    userprofile = os.environ.get("USERPROFILE")
    if userprofile:
        return Path(userprofile) / "Downloads"
    return Path("C:/Users/jim/Downloads")


def find_package(repo: Path) -> Path | None:
    root = repo / "runtime" / "build" / "windows-service"
    if not root.exists():
        return None
    pkgs = [p for p in root.glob("RTL-ADS-B-Tracker-Windows-Service-*") if p.is_dir()]
    pkgs = [p for p in pkgs if (p / "dist" / "third_party" / "dump1090" / "dump1090.exe").exists()]
    pkgs.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    return pkgs[0] if pkgs else None


def find_source_cfg(repo: Path, target_cfg: Path) -> Path | None:
    preferred = [
        repo / "build" / "third_party" / "dump1090" / "Dump1090-src" / "dump1090.cfg",
        repo / "dist" / "third_party" / "dump1090" / "dump1090.cfg",
    ]
    for p in preferred:
        if p.exists() and p.resolve() != target_cfg.resolve():
            return p

    for p in repo.rglob("dump1090.cfg"):
        try:
            if p.resolve() == target_cfg.resolve():
                continue
        except Exception:
            pass
        if p.exists() and "Dump1090-src" in p.as_posix():
            return p

    return None


def write_minimal_cfg(target_cfg: Path) -> None:
    target_cfg.write_text(
        """# Minimal Dump1090 runtime config generated by repair_and_test_dump1090_package.py
net                 = true
net-sbs-port        = 30003
net-ro-port         = 30002
net-bo-port         = 30005
http-port           = 8080
http-log            = false
logfile-daily       = false
""",
        encoding="utf-8",
    )


def backup_if_exists(path: Path, stamp: str) -> Path | None:
    if not path.exists():
        return None
    backup = path.with_name(f"{path.name}.bak_before_repair_{stamp}")
    if not backup.exists():
        shutil.copy2(path, backup)
    return backup


def copy_if_needed(src: Path, dst: Path, stamp: str) -> str:
    if not src.exists():
        return f"FAIL: source missing: {src}"
    if dst.exists():
        backup_if_exists(dst, stamp)
    shutil.copy2(src, dst)
    return f"PASS: copied {src} -> {dst}"


def copy_package_dlls(package: Path, dump_dir: Path, stamp: str) -> list[str]:
    lines: list[str] = []
    bin_dir = package / "bin"
    if not bin_dir.exists():
        lines.append(f"WARN: package bin folder not found: {bin_dir}")
        return lines

    dlls = sorted(bin_dir.glob("*.dll"))
    if not dlls:
        lines.append(f"WARN: no DLLs found in package bin folder: {bin_dir}")
        return lines

    for src in dlls:
        dst = dump_dir / src.name
        lines.append(copy_if_needed(src, dst, stamp))

    return lines


def make_env(package: Path, dump_dir: Path) -> dict[str, str]:
    env = os.environ.copy()
    path_parts = [
        str(dump_dir),
        str(package / "bin"),
        "C:/msys64/ucrt64/bin",
        env.get("PATH", ""),
    ]
    env["PATH"] = os.pathsep.join(path_parts)
    env.setdefault("DUMP1090_HOMEPOS", "38.814165,-105.189199")
    return env


def port_open(port: int) -> bool:
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.settimeout(0.5)
    try:
        sock.connect(("127.0.0.1", port))
        return True
    except Exception:
        return False
    finally:
        sock.close()


def summarize_body(body: str) -> str:
    if not body:
        return ""
    try:
        payload = json.loads(body)
    except Exception:
        return " ".join(body.split())[:260]
    if isinstance(payload, dict):
        if isinstance(payload.get("aircraft"), list):
            return f"JSON aircraft_count={len(payload['aircraft'])}; keys={','.join(list(payload.keys())[:8])}"
        return f"JSON keys={','.join(list(payload.keys())[:12])}"
    return f"JSON {type(payload).__name__}"


def http_get(url: str, timeout: int = 2) -> tuple[bool, str]:
    try:
        with urlopen(url, timeout=timeout) as response:
            body = response.read(1200).decode("utf-8", errors="replace")
            return True, f"HTTP {response.status}: {summarize_body(body)}"
    except HTTPError as exc:
        body = ""
        try:
            body = exc.read(800).decode("utf-8", errors="replace")
        except Exception:
            pass
        return False, f"HTTP {exc.code}: {summarize_body(body)}"
    except URLError as exc:
        return False, f"URL error: {exc.reason}"
    except Exception as exc:
        return False, f"{type(exc).__name__}: {exc}"


def run_dump1090_test(package: Path, dump_exe: Path, cfg: Path, lines: list[str]) -> bool:
    command = [
        str(dump_exe),
        "--config", str(cfg),
        "--device", EXPECTED_ADSB_DEVICE_INDEX,
        "--net",
    ]

    lines.append("Command:")
    lines.append("  " + " ".join(command))
    lines.append(f"Working directory: {dump_exe.parent}")

    proc = subprocess.Popen(
        command,
        cwd=str(dump_exe.parent),
        env=make_env(package, dump_exe.parent),
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )

    time.sleep(6)

    if proc.poll() is not None:
        out = ""
        try:
            out = proc.stdout.read() if proc.stdout else ""
        except Exception:
            pass
        lines.append(f"FAIL: dump1090 exited early with code {proc.returncode}.")
        lines.append("Output:")
        lines.append((out or "").rstrip())
        return False

    lines.append("PASS: dump1090 stayed running for initial startup window.")

    any_port = False
    lines.append("")
    lines.append("Port checks:")
    for port, label in PORTS_TO_CHECK:
        ok = port_open(port)
        any_port = any_port or ok
        lines.append(f"  {'PASS' if ok else 'FAIL'}: port {port} {label}")

    any_json = False
    lines.append("")
    lines.append("Aircraft JSON checks:")
    for url in JSON_URLS:
        ok, detail = http_get(url, timeout=2)
        any_json = any_json or ok
        lines.append(f"  {'PASS' if ok else 'FAIL'}: {url} -> {detail}")

    time.sleep(max(0, TEST_SECONDS - 6))

    if proc.poll() is None:
        lines.append("")
        lines.append("PASS: dump1090 was still running at end of test window.")
        still_running = True
    else:
        lines.append("")
        lines.append(f"FAIL: dump1090 exited during test window with code {proc.returncode}.")
        still_running = False

    lines.append("")
    lines.append("Stopping dump1090 test process...")
    if proc.poll() is None:
        try:
            proc.terminate()
            proc.wait(timeout=6)
        except Exception:
            try:
                proc.kill()
            except Exception:
                pass

    out = ""
    try:
        if proc.stdout:
            out = proc.stdout.read() or ""
    except Exception:
        pass

    lines.append("")
    lines.append("dump1090 output:")
    lines.append(out.rstrip())

    return bool(still_running and (any_port or any_json))


def main() -> int:
    repo = Path.cwd()
    downloads = downloads_dir()
    downloads.mkdir(parents=True, exist_ok=True)
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    out_path = downloads / f"rtl_windows_dump1090_repair_test_{stamp}.txt"

    lines: list[str] = []
    lines.append("RTL-Windows / RTP-Windows Dump1090 package repair and test")
    lines.append(f"Timestamp: {dt.datetime.now().isoformat(timespec='seconds')}")
    lines.append(f"Repo: {repo}")
    lines.append(f"Python: {sys.executable}")
    lines.append("")

    if not (repo / "web" / "app.js").exists():
        lines.append("FAIL: web/app.js not found. Run from repo root.")
        out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"FAIL: not run from repo root. Output saved to: {out_path}")
        return 2

    package = find_package(repo)
    if not package:
        lines.append("FAIL: could not find service package Dump1090 runtime.")
        out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"FAIL: service package not found. Output saved to: {out_path}")
        return 3

    dump_dir = package / "dist" / "third_party" / "dump1090"
    dump_exe = dump_dir / "dump1090.exe"
    target_cfg = dump_dir / "dump1090.cfg"

    lines.append("=" * 90)
    lines.append("Selected runtime")
    lines.append("=" * 90)
    lines.append(f"Package: {package}")
    lines.append(f"Dump1090 folder: {dump_dir}")
    lines.append(f"Dump1090 exe: {dump_exe}")
    lines.append(f"Target config: {target_cfg}")

    lines.append("")
    lines.append("=" * 90)
    lines.append("Repair actions")
    lines.append("=" * 90)

    source_cfg = find_source_cfg(repo, target_cfg)
    if source_cfg:
        lines.append(copy_if_needed(source_cfg, target_cfg, stamp))
    else:
        backup_if_exists(target_cfg, stamp)
        write_minimal_cfg(target_cfg)
        lines.append(f"WARN: no source dump1090.cfg found; wrote minimal config to {target_cfg}")

    lines.extend(copy_package_dlls(package, dump_dir, stamp))

    lines.append("")
    lines.append("Post-repair file checks:")
    for p in [dump_exe, target_cfg, dump_dir / "librtlsdr.dll", dump_dir / "libusb-1.0.dll", dump_dir / "libwinpthread-1.dll"]:
        lines.append(f"  {'PASS' if p.exists() else 'FAIL'}: {p}")

    lines.append("")
    lines.append("=" * 90)
    lines.append("Direct Dump1090 retest")
    lines.append("=" * 90)

    ok = run_dump1090_test(package, dump_exe, target_cfg, lines)

    lines.append("")
    lines.append("=" * 90)
    lines.append("Overall result")
    lines.append("=" * 90)

    if ok:
        lines.append("PASS: repaired packaged Dump1090 runtime starts directly and exposes network/http output.")
        lines.append("")
        lines.append("Next step:")
        lines.append("  Restart/reinstall the Windows service package and retest /api/aircraft.json.")
        rc = 0
    else:
        lines.append("FAIL: packaged Dump1090 runtime still does not start correctly after repair.")
        lines.append("Upload this file to ChatGPT.")
        rc = 1

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"{'PASS' if rc == 0 else 'FAIL'}: Dump1090 package repair/test complete.")
    print("Output saved to:")
    print(f"  {out_path}")
    print("Windows path:")
    print(f"  {str(out_path).replace('/', '\\\\')}")
    print("Upload this .txt file if FAIL, or restart/reinstall service if PASS.")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
